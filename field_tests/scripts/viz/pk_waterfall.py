"""Display data (not a prediction; no lock needed): exact Mukhanov-Sasaki P_R(k) for the SPECIES32 X point (D = 10, C = 8e-7)
over ln(k/k*) in [-1, 1]. All modes start together at the e-fold where the LOWEST k has k/aH = bd (as ms.spectra_fast does), so the
start error has a k-dependent phase and shows as interference fringes. Slices: plain Bunch-Davies start at bd = 5, 10, 20, then the exact
de Sitter start at bd = 20 (the fix used by spectra_fast). Writes apps/aegis_studio/pk_waterfall.js."""
import json, math, sys, time
import numpy as np
sys.path.insert(0, '.')
from tools.serapis_calc.p3s import V_np
from tools.serapis_calc.ms import Background
C, D, NSTAR = 8e-7, 10, 50.365416750265254
from scipy.interpolate import CubicSpline
b = math.sqrt(D - 2) / 2
_ph = np.linspace(math.log(math.sqrt(3) / 2) / b + 1e-4, math.log(200.0) / b, 30000)   # dense spline of the exact V (display accuracy)
_S = CubicSpline(_ph, V_np(_ph, C, D)); _dS = _S.derivative()
V = lambda p: float(_S(p)); dV = lambda p: float(_dS(p))
# start well up the plateau: y = 80 (N_tot > 100, room for every start)
bg = Background(V, dV, math.log(80.0) / b)
print('Nend', bg.Nend, flush=True)

from scipy.integrate import solve_ivp
def common_start(Nstar, dlnk, bd, ic):
    """ms.spectra_fast with a choice of initial mode: 'bd' = plain u = e^{-ik eta}/sqrt(2k); 'ds' = exact de Sitter (spectra_fast's own)."""
    Np = bg.Nend - Nstar; kp = bg.state(Np)[3]; ks = kp * np.exp(np.array(dlnk)); kmin = ks.min()
    f = lambda N: kmin / (np.exp(N - Np) * bg.state(N)[3]) - bd
    lo, hi = 0.0, Np
    for _ in range(80):
        mid = 0.5 * (lo + hi)
        if f(mid) > 0: lo = mid
        else: hi = mid
    N0 = lo; nk = len(ks)
    def rhs(N, y):
        p, pn, eps, H = bg.state(N); pnn = -(3 - eps) * pn - (3 - eps) * dV(p) / V(p)
        q2 = (ks / (np.exp(N - Np) * H)) ** 2; Y = y.reshape(nk, 8); o = np.empty_like(Y)
        R = Y[:, 0] + 1j * Y[:, 1]; Rp = Y[:, 2] + 1j * Y[:, 3]
        Rpp = -(3 - eps + 2 * pnn / pn) * Rp - q2 * R
        o[:, 0], o[:, 1], o[:, 2], o[:, 3] = Rp.real, Rp.imag, Rpp.real, Rpp.imag; o[:, 4:] = 0
        return o.ravel()
    p, pn, eps, H = bg.state(N0); a = np.exp(N0 - Np); pnn = -(3 - eps) * pn - (3 - eps) * dV(p) / V(p)
    z = a * pn; zn = z * (1 + pnn / pn)
    if ic == 'ds':
        eta = -1.0 / (a * H * (1 - eps)); u = (1 - 1j / (ks * eta)) / np.sqrt(2 * ks)
        un = ((-1j * ks * (1 - 1j / (ks * eta)) + 1j / (ks * eta ** 2)) / np.sqrt(2 * ks)) / (a * H)
    else:
        u = 1 / np.sqrt(2 * ks); un = -1j * (ks / (a * H)) * u
    R = u / z; Rn = un / z - u * zn / z ** 2; zero = np.zeros(nk)
    y0 = np.stack([R.real, R.imag, Rn.real, Rn.imag, zero, zero, zero, zero], 1).ravel()
    s = solve_ivp(rhs, [N0, Np + 12 + max(dlnk)], y0, rtol=1e-10, atol=1e-30, method='DOP853')
    Y = s.y[:, -1].reshape(nk, 8); lp = np.log(ks ** 3 * (Y[:, 0] ** 2 + Y[:, 1] ** 2) / (2 * np.pi ** 2))
    c = np.polyfit(np.array(dlnk), lp, 2); return lp, 1 + c[1]
dl = tuple(np.round(np.linspace(-1, 1, int(sys.argv[1]) if len(sys.argv) > 1 else 121), 5))
slices = [('bd', 5.0), ('bd', 10.0), ('bd', 20.0), ('ds', 20.0)]
out = []
for ic, bd in slices:
    t = time.time(); lp, ns = common_start(NSTAR, dl, bd, ic)
    out.append(dict(ic=ic, bd=bd, lnPR=[float(x) for x in lp], ns=float(ns)))
    print(ic, bd, round(time.time() - t, 1), 's  n_s(quadratic fit)', ns, flush=True)
data = dict(point='SPECIES32 X (D=10, C=8e-7, N*=50.37)', dlnk=[float(x) for x in dl], slices=out)
open('apps/aegis_studio/pk_waterfall.js', 'w').write('// generated by field_tests/scripts/viz/pk_waterfall.py\nwindow.PK_WATERFALL = ' + json.dumps(data) + ';\n')
