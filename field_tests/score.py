"""Score every open field test by its locked rule and write field_tests/STATUS.md (+ STATUS.json).
    python field_tests/score.py            # results from cmb-fit/results (or $TWIST_RESULTS)
No fitting here. Missing runs show as pending. The locked scorers in scorers/ are the release copies, changed only to
read $TWIST_RESULTS (original SHA-256 in scorers/ORIGINAL_SHA256.txt)."""
import json
import os
import subprocess
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
RES = os.environ.get("TWIST_RESULTS") or os.path.join(ROOT, "cmb-fit", "results")
TESTS = json.load(open(os.path.join(HERE, "TESTS.json"), encoding="utf-8"))
OUT = os.path.join(HERE, "out")


def run_scorer(name):
    os.makedirs(OUT, exist_ok=True)
    env = dict(os.environ, TWIST_RESULTS=RES)
    parts = name.split()
    script = os.path.join(ROOT, parts[0]) if "/" in parts[0] else os.path.join(HERE, "scorers", parts[0])
    r = subprocess.run([sys.executable, script, *parts[1:]], cwd=OUT, env=env, capture_output=True, text=True)
    return r.stdout.strip() + (("\n" + r.stderr.strip()) if r.returncode else "")


def done(names):
    return [n for n in names if os.path.exists(os.path.join(RES, f"cmp_{n}.json"))]


def gate_ok(t):
    """True, False, or None when the gate has not been run yet."""
    g = t.get("gate")
    if not g:
        return True
    p = os.path.join(HERE, g["file"])
    if not os.path.exists(p):
        return None
    v = json.load(open(p)).get(g["key"])
    return v == g["equals"] if "equals" in g else abs(v) <= g["max_abs"]


def main():
    rows, logs = [], {}
    for t in TESTS["tests"]:
        runs = t.get("runs", [])
        have = done(runs)
        gate = gate_ok(t)
        status = ("draft rule: lock it first (S8_WL/SETUP.md)" if t.get("draft") else
                  "code missing" if t.get("code_missing") else
                  "gate not run yet (build + regression first)" if gate is None else
                  "gate FAILED: no fits count" if not gate else
                  "complete" if runs and len(have) == len(runs) else
                  f"{len(have)}/{len(runs)} runs" if runs else "external")
        rows.append({"id": t["id"], "title": t["title"], "where": t["where"], "status": status,
                     "rule": t["rule"], "locked": t.get("locked")})
        if t.get("scorer") and t["scorer"] not in logs and have:
            logs[t["scorer"]] = run_scorer(t["scorer"])
    stamp = time.strftime("%Y-%m-%d %H:%M %Z")
    md = [f"# Field tests: status ({stamp})", "",
          "Generated by `field_tests/score.py`. Verdicts come only from the locked scorers below.", "",
          "| Test | Where | Runs | Rule (locked) |", "|---|---|---|---|"]
    md += [f"| **{r['id']}** {r['title']} | {r['where']} | {r['status']} | `{r['rule']}` ({r['locked']}) |" for r in rows]
    for k, v in logs.items():
        md += ["", f"## {k}", "", "```", v, "```"]
    open(os.path.join(HERE, "STATUS.md"), "w", encoding="utf-8").write("\n".join(md) + "\n")
    json.dump({"generated": stamp, "results_dir": RES, "tests": rows, "scorer_output": logs},
              open(os.path.join(HERE, "STATUS.json"), "w", encoding="utf-8"), indent=1)
    print("\n".join(md))


if __name__ == "__main__":
    main()
