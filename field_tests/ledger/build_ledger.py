"""Pre-registration ledger (V9): every locked rule, its SHA-256 re-verified against the file on disk, its lock time,
and every recorded verdict, failures at the same size as passes.
    python build_ledger.py [--cubemind PATH]   -> LEDGER.md, ledger.json (beside this script)
Sources: aegis/field_tests/rules/*.sha256, cubemind/*.sha256 (if present), cubemind/CLAIMS_INDEX.md (verdicts to
2 Nov), aegis/CURRENT_MODEL.md (verdicts since). Nothing is edited; a hash mismatch is reported, never repaired."""
import hashlib
import json
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
AEGIS = os.path.abspath(os.path.join(HERE, "..", ".."))
CUBE = sys.argv[sys.argv.index("--cubemind") + 1] if "--cubemind" in sys.argv else os.path.join(AEGIS, "..", "cubemind")


def sha(path):
    return hashlib.sha256(open(path, "rb").read()).hexdigest()


def check(path, h):
    """True = exact match; 'line endings only' = matches after CRLF -> LF (a Windows checkout); False = content differs."""
    if not os.path.exists(path):
        return "file missing"
    if sha(path) == h:
        return True
    if hashlib.sha256(open(path, "rb").read().replace(b"\r\n", b"\n")).hexdigest() == h:
        return "line endings only"
    return False


def git_first_commit(path):
    try:
        out = subprocess.run(["git", "log", "--diff-filter=A", "--format=%cI", "--", os.path.basename(path)],
                             cwd=os.path.dirname(path), capture_output=True, text=True, timeout=30).stdout.split()
        return out[-1] if out else ""
    except Exception:
        return ""


def rules(folder, origin):
    rows = []
    if not os.path.isdir(folder):
        return rows
    for f in sorted(os.listdir(folder)):
        if not f.endswith(".sha256"):
            continue
        for raw in open(os.path.join(folder, f), encoding="utf-8").read().splitlines():
            line = raw.split()
            if len(line) < 1 or not re.fullmatch(r"[0-9a-f]{64}", line[0]):
                continue
            h, target = line[0], (line[1] if len(line) > 1 else f[:-7])
            m = re.search(r"locked\s+(\S+)", raw)
            rows.append({"rule": target, "origin": origin, "sha256": h,
                         "verified": check(os.path.join(folder, target), h),
                         "lock_time": (m.group(1) if m else "") or git_first_commit(os.path.join(folder, f))})
    return rows


def table_rows(path, origin):
    out = []
    if not os.path.exists(path):
        return out
    for line in open(path, encoding="utf-8"):
        if not line.startswith("| ") or line.startswith("| #") or line.startswith("| Test |") or set(line) <= set("|- \n"):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if origin == "CLAIMS_INDEX" and len(cells) >= 4:
            out.append({"id": cells[0], "test": cells[1], "verdict": cells[2], "rule": cells[3], "source": origin})
        elif origin == "CURRENT_MODEL" and len(cells) >= 3:
            out.append({"id": "", "test": cells[0], "verdict": cells[2], "result": cells[1], "source": origin})
        elif origin == "CURRENT_MODEL" and len(cells) == 2:
            out.append({"id": "", "test": cells[0], "verdict": "(running) " + cells[1], "source": origin})
    return out


def classify(v):
    t = v.upper()
    for k, lab in (("NOT FIXED", "fail"), ("MIXED", "mixed"), ("FAIL", "fail"), ("EXCLUDED", "fail"), ("DOES NOT", "fail"), ("NOT COMPETITIVE", "fail"),
                   ("DISFAVOURED", "fail"), ("OVER", "fail"), ("LOSES", "fail"), ("NO LOCK", "fail"),
                   ("RUNNING", "open"), ("OPEN", "open"), ("NO VERDICT", "open"), ("MIXED", "mixed"), ("TIE", "neutral"),
                   ("NEUTRAL", "neutral"), ("CANNOT TELL", "neutral"), ("WEAK", "neutral"), ("MILD", "neutral"),
                   ("PASS", "pass"), ("BEATS", "pass"), ("SUPPORTED", "pass"), ("PREFERRED", "pass"),
                   ("CONSISTENT", "pass"), ("SURVIVES", "pass"), ("STABLE", "pass"), ("FAVOURED", "pass"),
                   ("STAYS", "pass"), ("COMPETITIVE", "pass")):
        if k in t:
            return lab
    return "reported"


def main():
    R = rules(os.path.join(AEGIS, "field_tests", "rules"), "AEGIS") + rules(CUBE, "CubeMind")
    V = table_rows(os.path.join(CUBE, "CLAIMS_INDEX.md"), "CLAIMS_INDEX") + \
        table_rows(os.path.join(AEGIS, "CURRENT_MODEL.md"), "CURRENT_MODEL")
    for v in V:
        v["class"] = classify(v["verdict"])
    counts = {}
    for v in V:
        counts[v["class"]] = counts.get(v["class"], 0) + 1
    bad = [r for r in R if r["verified"] not in (True, "line endings only")]
    json.dump({"rules": R, "verdicts": V, "counts": counts}, open(os.path.join(HERE, "ledger.json"), "w"), indent=1)
    L = ["# Pre-registration ledger (generated by build_ledger.py; do not edit by hand)", "",
         f"**Locked files:** {len(R)}; SHA-256 re-verified against the file on disk: exact "
         f"{sum(r['verified'] is True for r in R)}, identical except Windows line endings "
         f"{sum(r['verified'] == 'line endings only' for r in R)}, content differs or missing: {len(bad)}.",
         f"**Recorded verdicts:** {len(V)} — " + ", ".join(f"{k} {n}" for k, n in sorted(counts.items())) + ".",
         "Classes are a keyword sort of the verdict text for counting only; the verdict text itself is authoritative.", "",
         "## Verdicts", "", "| # | Test | Verdict | Class | Source |", "|---|---|---|---|---|"]
    for v in V:
        L.append(f"| {v['id']} | {v['test']} | {v['verdict']} | {v['class']} | {v['source']} |")
    L += ["", "## Locked rules and hash check", "", "| Rule | Origin | Lock time | SHA-256 (first 12) | Verified |",
          "|---|---|---|---|---|"]
    for r in R:
        L.append(f"| {r['rule']} | {r['origin']} | {r['lock_time']} | {r['sha256'][:12]} | {r['verified']} |")
    open(os.path.join(HERE, "LEDGER.md"), "w", encoding="utf-8").write("\n".join(L) + "\n")
    print(f"rules {len(R)}, verified {sum(r['verified'] is True for r in R)}, problems {len(bad)}; verdicts {len(V)} {counts}")
    for r in bad:
        print("  PROBLEM:", r["origin"], r["rule"], r["verified"])


if __name__ == "__main__":
    main()
