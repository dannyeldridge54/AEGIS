"""Build docs/D_INDEX.md from the D-notes file: one line per note (number, date, title, verdict).
Run from the repo root:  python tools/dnotes/build_index.py
Dates are the git author date of the line holding the note's heading (git blame)."""
import re, subprocess, datetime, pathlib
NOTES = "theory/pending_docs/D72_D75_weak_spots.md"
OUT = pathlib.Path("docs/D_INDEX.md")
lines = pathlib.Path(NOTES).read_text(encoding="utf-8").splitlines()
blame = subprocess.run(["git", "blame", "--line-porcelain", NOTES], capture_output=True, text=True).stdout
times, cur = [], None
for b in blame.splitlines():
    if b.startswith("author-time "): cur = int(b.split()[1])
    elif b.startswith("\t"): times.append(cur)
head = re.compile(r"^(?:##\s+|\*\*)(D\d+[a-z]?)\b\s*(.*)")
notes = []
for i, l in enumerate(lines):
    m = head.match(l)
    if not m: continue
    num, rest = m.group(1), m.group(2).split("**")[0].strip(" —-:().")
    if any(n[0] == num for n in notes) and not l.startswith("##"):
        continue  # older bold-style notes: later paragraphs of the same note
    body = []
    for l2 in lines[i + 1:i + 60]:
        if head.match(l2): break
        body.append(l2)
    verdict = ""
    for l2 in body:
        k = l2.upper().find("VERDICT")
        if k >= 0:
            verdict = re.sub(r"\s+", " ", l2[k + 7:].lstrip(" :(").split(". ")[0])[:140]; break
    t = times[i] if i < len(times) and times[i] else None
    date = datetime.datetime.fromtimestamp(t, datetime.timezone.utc).strftime("%Y-%m-%d") if t else ""
    title = re.sub(r"\s+", " ", rest)[:120].replace("|", "/")
    notes.append((num, date, title, verdict.replace("|", "/")))
def key(n):
    m = re.match(r"D(\d+)([a-z]?)", n[0]); return (int(m.group(1)), m.group(2))
notes.sort(key=key)
dups = sorted({n[0] for n in notes if sum(1 for x in notes if x[0] == n[0]) > 1}, key=lambda d: key((d,)))
out = ["# D-note index", "", f"Generated by `python tools/dnotes/build_index.py` from `{NOTES}` ({len(notes)} notes). Do not edit by hand.", ""]
if dups:
    out += [f"Numbers used more than once (historical): {', '.join(dups)}", ""]
out += ["| D | Date | Title | Verdict |", "|---|---|---|---|"]
out += [f"| {n} | {d} | {t} | {v} |" for n, d, t, v in notes]
OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"wrote {OUT} ({len(notes)} notes, {len(dups)} duplicated numbers)")
